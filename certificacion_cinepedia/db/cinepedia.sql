CREATE DATABASE cinepedia CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE cinepedia;
CREATE TABLE usuarios (
 id INT AUTO_INCREMENT PRIMARY KEY, nombre VARCHAR(80) NOT NULL, apellido VARCHAR(80) NOT NULL,
 email VARCHAR(150) NOT NULL UNIQUE, password_hash VARCHAR(255) NOT NULL,
 creado_en TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE peliculas (
 id INT AUTO_INCREMENT PRIMARY KEY, usuario_id INT NOT NULL, nombre VARCHAR(150) NOT NULL UNIQUE,
 director VARCHAR(120) NOT NULL, fecha_estreno DATE NOT NULL, sinopsis TEXT NOT NULL,
 creado_en TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (usuario_id) REFERENCES usuarios(id) ON DELETE CASCADE
);
CREATE TABLE comentarios (
 id INT AUTO_INCREMENT PRIMARY KEY, pelicula_id INT NOT NULL, usuario_id INT NOT NULL,
 contenido VARCHAR(1000) NOT NULL, creado_en TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (pelicula_id) REFERENCES peliculas(id) ON DELETE CASCADE,
 FOREIGN KEY (usuario_id) REFERENCES usuarios(id) ON DELETE CASCADE
);
